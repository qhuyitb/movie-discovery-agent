#!/usr/bin/env python3
"""Replay one conversation against the LLM backend and save it.

The offline transcripts are deterministic; this one is not, and it costs money to
produce, so it lives in its own script and its output is committed as evidence
that the LLM path actually runs. The turns are chosen to test the two things that
matter about this backend: whether it plans the tools correctly, and whether it
stays inside the tool results when the question invites it not to.

Run:  OPENAI_API_KEY=... python eval/run_llm_transcript.py [--model gpt-4o-mini]
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from movieagent import config                     # noqa: E402
from movieagent.agent import build_agent          # noqa: E402
from movieagent.tools import MovieTools           # noqa: E402

TURNS = [
    (1,  "What do people with similar taste to mine think about Pulp Fiction?"),
    (30, "I liked Toy Story but I'm tired of animated movies - what else?"),
    (1,  "Is Pulp Fiction better than The Godfather? What did critics say at the time?"),
    (1,  "Tell me about The Matrix - what happens in it and what do people like me think of it?"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", default="openai", choices=["openai", "anthropic"])
    ap.add_argument("--model", default="gpt-4o-mini")
    args = ap.parse_args()

    tools = MovieTools.bootstrap()
    lines = [
        "# 05 LLM backend",
        "",
        f"*Generated by `python eval/run_llm_transcript.py --backend {args.backend} "
        f"--model {args.model}` on {dt.date.today().isoformat()}. Unlike the other "
        "transcripts this one is **not** reproducible verbatim - the model is sampled at "
        "temperature 0.3 and needs an API key. It is committed so the LLM path can be "
        "reviewed without running it.*",
        "",
        "The four turns test the two things that separate this backend from the offline one: "
        "whether the model plans the tool calls correctly, and whether it stays inside the "
        "tool results when the question invites outside knowledge. Turns 3 and 4 are "
        "deliberately baited.",
        "",
    ]

    for uid, message in TURNS:
        agent = build_agent(args.backend, user_id=uid, tools=tools, model=args.model)
        turn = agent.chat(message)
        lines.append(f"---\n\n**you>** *(as user {uid})* {message}\n")
        lines.append("<details><summary>tool calls</summary>\n")
        lines.append("```")
        lines.extend(turn.trace_lines() or ["(none)"])
        lines.append("```")
        lines.append("</details>\n")
        lines.append("```text")
        lines.append(turn.text)
        lines.append("```\n")
        print(f"  turn done: {message[:50]}...")

    out = config.OUTPUT_DIR / "transcripts" / "05_llm_backend.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
