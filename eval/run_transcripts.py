#!/usr/bin/env python3
"""Replay scripted conversations and save them as markdown.

These are the reproducible sample conversations asked for in the brief. Because
the default backend is deterministic and offline, re-running this reproduces the
committed transcripts byte for byte.

Run:  python eval/run_transcripts.py    -> outputs/transcripts/*.md
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from movieagent import config                     # noqa: E402
from movieagent.agent import build_agent          # noqa: E402
from movieagent.tools import MovieTools           # noqa: E402

CONVERSATIONS = [
    ("01_user1_action_comedy_fan", 1,
     "User 1 - 190 ratings, average 4.33, action/comedy fan. The dense-history case.",
     ["I'm user 1",
      "What should I watch tonight?",
      "Why do you think I'd like that?",
      "What do people with similar taste to mine think about Pulp Fiction?",
      "What's my blind spot? What genres am I missing?"]),

    ("02_user15_scifi", 15,
     "User 15 - 85 ratings, average 3.55, sci-fi leaning. Tests content search and multi-hop.",
     ["I'm user 15",
      "I want a dark psychological thriller with a twist",
      "Tell me about Shutter Island",
      "What do people with similar taste to mine think about Shutter Island?",
      "movies like Aliens"]),

    ("03_user30_cold_start", 30,
     "User 30 - only 18 ratings, average 4.61. The cold-start case, plus a hard constraint.",
     ["I'm user 30",
      "I liked Toy Story but I'm tired of animated movies - what else?",
      "Why do you think I'd like that?",
      "Who has taste like mine?",
      "What's my blind spot?"]),

    ("04_edge_cases", None,
     "Deliberate edge cases: no user id, a film that is not in this filtered catalogue, "
     "a nonexistent user, and an unparseable request.",
     ["What should I watch tonight?",
      "I'm user 4242",
      "I'm user 1",
      "What do people like me think about The Matrix?",
      "banana helicopter",
      "I want a feel good comedy about friendship"]),
]


def main() -> None:
    tools = MovieTools.bootstrap()
    out_dir = config.OUTPUT_DIR / "transcripts"
    out_dir.mkdir(parents=True, exist_ok=True)

    index_lines = ["# Sample conversations\n",
                   "01-04 are generated by `python eval/run_transcripts.py` with the default "
                   "offline backend, so they are reproducible verbatim.\n"]

    for slug, uid, blurb, turns in CONVERSATIONS:
        agent = build_agent("heuristic", user_id=uid, tools=tools)
        lines = [f"# {slug.replace('_', ' ')}\n", f"*{blurb}*\n"]
        for message in turns:
            turn = agent.chat(message)
            lines.append(f"---\n\n**you>** {message}\n")
            lines.append("<details><summary>tool calls</summary>\n")
            lines.append("```")
            lines.extend(turn.trace_lines() or ["(none)"])
            for note in turn.notes:
                lines.append(f"note: {note}")
            lines.append("```")
            lines.append("</details>\n")
            lines.append("```text")
            lines.append(turn.text)
            lines.append("```\n")
        (out_dir / f"{slug}.md").write_text("\n".join(lines))
        index_lines.append(f"- [`{slug}.md`]({slug}.md) - {blurb}")
        print(f"wrote {out_dir / (slug + '.md')}")

    # 05 comes from run_llm_transcript.py, which costs money and needs a key; keep it in
    # the index if it has been generated so re-running this script does not drop it.
    llm = out_dir / "05_llm_backend.md"
    if llm.exists():
        index_lines.append(
            "- [`05_llm_backend.md`](05_llm_backend.md) - the optional LLM backend "
            "(gpt-4o-mini) on four turns, two of them baited to test grounding. "
            "Generated by `eval/run_llm_transcript.py`; needs an API key and is not "
            "reproducible verbatim.")

    (out_dir / "README.md").write_text("\n".join(index_lines) + "\n")


if __name__ == "__main__":
    main()
